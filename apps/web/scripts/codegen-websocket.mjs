#!/usr/bin/env node
// Generate WebSocket route artefacts from specs/contracts/realtime/websocket/*.yaml.
// Outputs (one source of truth → both consumers, no hand-written route literals):
//   - apps/api/src/Throne.Contracts/Generated/TerminalWebSocketRoutes.g.cs (C# route templates)
//   - apps/web/src/shared/realtime/generated/terminal-routes.ts (base-relative path builders)
// Mirrors the OpenAPI generator split: C# keeps the full `/api/v1/...` route (like the
// generated controller `Route` attributes); TS strips the `/api/v1` base (like the generated
// endpoints.ts builders fed to apiUrl()). Do not edit generated files.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WEB_DIR = resolve(__dirname, "..");
const ROOT_DIR = resolve(WEB_DIR, "../..");
const TERMINAL_YAML = resolve(
  ROOT_DIR,
  "specs/contracts/realtime/websocket/terminal.yaml"
);
const TS_OUT = resolve(
  WEB_DIR,
  "src/shared/realtime/generated/terminal-routes.ts"
);
const CS_OUT = resolve(
  ROOT_DIR,
  "apps/api/src/Throne.Contracts/Generated/TerminalWebSocketRoutes.g.cs"
);

const API_PREFIX = "/api/v1";

function toRepoRelative(path) {
  return path.replace(ROOT_DIR + "/", "");
}

function pascalCase(parts) {
  return parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");
}

// /api/v1/intents/{intent_id}/terminal/ws -> "IntentsTerminalWs"
// Drops the version prefix and path params so the name reads off the resource path.
function channelName(path) {
  const parts = path
    .split("/")
    .filter(Boolean)
    .filter(
      (seg) => seg !== "api" && !/^v\d+$/.test(seg) && !seg.startsWith("{")
    );
  return pascalCase(parts);
}

function camelCase(pascal) {
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

function params(path) {
  return [...path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
}

function banner() {
  return [
    "// <auto-generated/>",
    "// This file is generated. Do not edit manually.",
    `// Source of truth: ${toRepoRelative(TERMINAL_YAML)}`,
    "// Regenerate via: scripts/quality/codegen-frontend.sh",
    ""
  ].join("\n");
}

function loadChannels() {
  const doc = parseYaml(readFileSync(TERMINAL_YAML, "utf8"));
  const channels = doc.channels ?? {};
  const ordered = Object.keys(channels).sort((a, b) => a.localeCompare(b));
  if (ordered.length === 0) {
    throw new Error(`No channels in ${TERMINAL_YAML}`);
  }
  return ordered;
}

function generateCs(channels) {
  const lines = [banner()];
  lines.push("namespace Throne.Terminal.Contracts.Generated;");
  lines.push("");
  lines.push("/// <summary>");
  lines.push(
    "/// Canonical route templates for embedded-terminal WebSocket channels."
  );
  lines.push(
    "/// Generated from specs/contracts/realtime/websocket/terminal.yaml."
  );
  lines.push("/// </summary>");
  lines.push("public static class TerminalWebSocketRoutes");
  lines.push("{");
  for (const path of channels) {
    lines.push(`    public const string ${channelName(path)} = "${path}";`);
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function generateTs(channels) {
  const lines = [banner()];
  lines.push("export const terminalWebSocketEndpoints = {");
  for (const path of channels) {
    const relative = path.startsWith(API_PREFIX)
      ? path.slice(API_PREFIX.length)
      : path;
    const args = params(path);
    const signature = args.map((p) => `${p}: string`).join(", ");
    const tpl = relative.replace(/\{(\w+)\}/g, (_, name) => `\${${name}}`);
    const expr = args.length > 0 ? "`" + tpl + "`" : `"${relative}"`;
    lines.push(`  ${camelCase(channelName(path))}: (${signature}) => ${expr},`);
  }
  lines.push("} as const;");
  lines.push("");
  return lines.join("\n");
}

function main() {
  const channels = loadChannels();

  mkdirSync(dirname(CS_OUT), { recursive: true });
  writeFileSync(CS_OUT, generateCs(channels));

  mkdirSync(dirname(TS_OUT), { recursive: true });
  writeFileSync(TS_OUT, generateTs(channels));

  console.log(
    `WebSocket route codegen complete (${String(channels.length)} channel(s)).`
  );
}

main();
